"""Telegram integration bridge supporting Bot API and Telethon Userbot.

Enables Suzu to:
1. Send native voice notes (OGG Opus) generated by her voice engine.
2. Send circular video notes (MP4 1:1) with her 3D VRM avatar in selfie mode.
3. Automatically resolve the target recipient by matching active Telegram Desktop window title.
4. Listen for incoming messages and dispatch them to the event bus.
"""

from __future__ import annotations

import asyncio
import logging
from pathlib import Path
from typing import Any

import aiohttp

from daemon.bus import EventBus, TelegramMessage
from daemon.config import TelegramConfig
from daemon.media_generator import MediaGenerator

try:
    from telethon import TelegramClient, events
    from telethon.tl.types import DocumentAttributeVideo

    HAVE_TELETHON = True
except ImportError:
    HAVE_TELETHON = False
    TelegramClient = None  # type: ignore[assignment, misc]
    events = None  # type: ignore[assignment]
    DocumentAttributeVideo = None  # type: ignore[assignment, misc]

logger = logging.getLogger(__name__)


class TelegramBridge:
    """Hybrid Telegram interface: Bot API (HTTP) and Telethon (MTProto Userbot)."""

    def __init__(
        self,
        config: TelegramConfig,
        bus: EventBus,
        vision: Any | None = None,
        session_dir: Path | None = None,
    ) -> None:
        self.cfg = config
        self.bus = bus
        self.vision = vision
        self._session_dir = session_dir or (Path.home() / ".config" / "vtuber")
        self._session_dir.mkdir(parents=True, exist_ok=True)

        self._http_session: aiohttp.ClientSession | None = None
        self._telethon_client: Any | None = None
        self._poll_task: asyncio.Task[None] | None = None
        self._running = False
        self._last_update_id = 0

    @property
    def is_bot_available(self) -> bool:
        """Check if Telegram Bot API is configured."""
        return bool(self.cfg.bot_token and self.cfg.mode in ("bot", "both"))

    @property
    def is_userbot_available(self) -> bool:
        """Check if Telethon userbot credentials are provided."""
        return bool(
            HAVE_TELETHON
            and self.cfg.api_id
            and self.cfg.api_hash
            and self.cfg.mode in ("userbot", "both")
        )

    async def start(self) -> None:
        """Initialize HTTP session, Telethon client and background polling."""
        if not self.cfg.enabled:
            logger.info("Telegram bridge is disabled in configuration")
            return

        self._running = True
        self._http_session = aiohttp.ClientSession(
            timeout=aiohttp.ClientTimeout(total=45.0, connect=10.0)
        )

        if self.is_userbot_available:
            await self._init_telethon()

        if self.is_bot_available:
            self._poll_task = asyncio.create_task(self._bot_polling_loop())

        logger.info(
            "Telegram bridge started (Bot: %s, Userbot: %s)",
            "enabled" if self.is_bot_available else "disabled",
            "enabled" if self.is_userbot_available else "disabled",
        )

    async def stop(self) -> None:
        """Gracefully shutdown clients and tasks."""
        self._running = False
        if self._poll_task and not self._poll_task.done():
            self._poll_task.cancel()
            try:
                await self._poll_task
            except asyncio.CancelledError:
                pass

        if self._telethon_client:
            try:
                await self._telethon_client.disconnect()
            except Exception as exc:  # noqa: BLE001
                logger.debug("Error disconnecting Telethon: %s", exc)
            self._telethon_client = None

        if self._http_session and not self._http_session.closed:
            await self._http_session.close()
            self._http_session = None

        logger.info("Telegram bridge stopped")

    async def _init_telethon(self) -> None:
        """Connect Telethon client and attach event listeners."""
        session_file = str(self._session_dir / self.cfg.session_name)
        try:
            self._telethon_client = TelegramClient(
                session_file, self.cfg.api_id, self.cfg.api_hash
            )
            await self._telethon_client.connect()
            if not await self._telethon_client.is_user_authorized():
                logger.warning(
                    "Telethon session '%s' is not authorized yet. Userbot features require authorization.",
                    session_file,
                )
            else:
                me = await self._telethon_client.get_me()
                logger.info(
                    "Telethon Userbot connected as: %s (@%s)",
                    getattr(me, "first_name", "User"),
                    getattr(me, "username", "unknown"),
                )

                @self._telethon_client.on(events.NewMessage(incoming=True))
                async def _on_userbot_message(event: Any) -> None:
                    await self._handle_incoming_telethon_msg(event)

        except Exception as exc:  # noqa: BLE001
            logger.error("Failed to initialize Telethon Userbot: %s", exc)
            self._telethon_client = None

    async def resolve_target(self, fallback_title: str | None = None) -> Any:
        """Determine target Telegram chat_id or entity based on screen context or config default."""
        title = fallback_title
        if not title and self.vision:
            app = getattr(self.vision, "active_app", "").lower()
            if "telegram" in app or "telegramdesktop" in app:
                title = getattr(self.vision, "active_title", "")

        # 1. Try matching with active Telegram Desktop dialog via Telethon
        if title and self._telethon_client and await self._telethon_client.is_user_authorized():
            matched = await self._find_telethon_dialog_by_title(title)
            if matched:
                logger.info("Matched active screen dialog '%s' to Telegram entity: %s", title, matched)
                return matched

        # 2. Fallback to default chat ID
        if self.cfg.default_chat_id:
            return self.cfg.default_chat_id

        return None

    async def _find_telethon_dialog_by_title(self, window_title: str) -> Any | None:
        """Search Telethon recent dialogs matching desktop window title."""
        if not self._telethon_client:
            return None

        # Clean Telegram Desktop title format (e.g., "Ivan", "Dev Group", "Telegram")
        clean_title = window_title.strip()
        for suffix in (" - Telegram", " — Telegram"):
            if clean_title.endswith(suffix):
                clean_title = clean_title[: -len(suffix)].strip()

        if not clean_title or clean_title.lower() in ("telegram", "telegram desktop"):
            return None

        try:
            dialogs = await self._telethon_client.get_dialogs(limit=30)
            clean_lower = clean_title.lower()
            for dlg in dialogs:
                name = (dlg.name or "").strip().lower()
                if clean_lower in name or name in clean_lower:
                    return dlg.entity
        except Exception as exc:  # noqa: BLE001
            logger.debug("Failed searching dialogs: %s", exc)

        return None

    # --- Messaging API ---

    async def send_text(self, text: str, target: Any = None) -> bool:
        """Send text message to Telegram recipient."""
        dest = target or await self.resolve_target()
        if not dest:
            logger.warning("Cannot send text: no recipient resolved")
            return False

        # Prefer Telethon Userbot if available and authorized
        if self._telethon_client and await self._telethon_client.is_user_authorized():
            try:
                await self._telethon_client.send_message(dest, text)
                logger.info("Sent Telegram text message via Userbot to %s", dest)
                return True
            except Exception as exc:  # noqa: BLE001
                logger.warning("Userbot send_message failed: %s; falling back to Bot API", exc)

        # Bot API fallback
        if self.is_bot_available:
            return await self._bot_send_message(dest, text)

        return False

    async def send_voice(
        self, audio_bytes: bytes, caption: str | None = None, target: Any = None
    ) -> bool:
        """Encode audio into OGG Opus and send as a native Telegram Voice Note."""
        dest = target or await self.resolve_target()
        if not dest:
            logger.warning("Cannot send voice: no recipient resolved")
            return False

        ogg_path = MediaGenerator.encode_voice_note(audio_bytes)
        try:
            # 1. Telethon Userbot
            if self._telethon_client and await self._telethon_client.is_user_authorized():
                try:
                    await self._telethon_client.send_file(
                        dest,
                        str(ogg_path),
                        voice_note=True,
                        caption=caption or "",
                    )
                    logger.info("Sent Telegram voice note via Userbot to %s", dest)
                    return True
                except Exception as exc:  # noqa: BLE001
                    logger.warning("Userbot send voice failed: %s; falling back to Bot API", exc)

            # 2. Bot API
            if self.is_bot_available:
                return await self._bot_send_voice(dest, ogg_path, caption=caption)

            return False
        finally:
            try:
                ogg_path.unlink(missing_ok=True)
            except OSError:
                pass

    async def send_round_video(
        self,
        video_bytes: bytes,
        audio_bytes: bytes | None = None,
        target: Any = None,
        duration: int | None = None,
    ) -> bool:
        """Encode avatar canvas stream into 1:1 H.264 Baseline MP4 and send as a Telegram Round Video Note."""
        dest = target or await self.resolve_target()
        if not dest:
            logger.warning("Cannot send round video: no recipient resolved")
            return False

        mp4_path = MediaGenerator.encode_round_video(video_bytes, audio_bytes=audio_bytes)
        try:
            # 1. Telethon Userbot
            if self._telethon_client and await self._telethon_client.is_user_authorized():
                try:
                    attr = DocumentAttributeVideo(
                        duration=duration or 5,
                        w=384,
                        h=384,
                        round_message=True,
                        supports_streaming=True,
                    )
                    await self._telethon_client.send_file(
                        dest,
                        str(mp4_path),
                        video_note=True,
                        attributes=[attr],
                    )
                    logger.info("Sent Telegram video note (round circle) via Userbot to %s", dest)
                    return True
                except Exception as exc:  # noqa: BLE001
                    logger.warning("Userbot send round video failed: %s; falling back to Bot API", exc)

            # 2. Bot API
            if self.is_bot_available:
                return await self._bot_send_video_note(dest, mp4_path, duration=duration)

            return False
        finally:
            try:
                mp4_path.unlink(missing_ok=True)
            except OSError:
                pass

    # --- Telegram Bot API HTTP implementation ---

    async def _bot_send_message(self, chat_id: Any, text: str) -> bool:
        """Send message via Bot API sendMessage."""
        if not self._http_session:
            return False

        url = f"https://api.telegram.org/bot{self.cfg.bot_token}/sendMessage"
        payload = {"chat_id": chat_id, "text": text}
        try:
            async with self._http_session.post(url, json=payload) as resp:
                res = await resp.json()
                if res.get("ok"):
                    logger.info("Sent Telegram message via Bot API to %s", chat_id)
                    return True
                logger.error("Bot API sendMessage error: %s", res)
                return False
        except Exception as exc:  # noqa: BLE001
            logger.error("HTTP error sending Telegram message: %s", exc)
            return False

    async def _bot_send_voice(self, chat_id: Any, ogg_path: Path, caption: str | None = None) -> bool:
        """Send voice note via Bot API sendVoice."""
        if not self._http_session:
            return False

        url = f"https://api.telegram.org/bot{self.cfg.bot_token}/sendVoice"
        data = aiohttp.FormData()
        data.add_field("chat_id", str(chat_id))
        if caption:
            data.add_field("caption", caption)

        ogg_bytes = await asyncio.to_thread(ogg_path.read_bytes)
        data.add_field(
            "voice",
            ogg_bytes,
            filename="voice.ogg",
            content_type="audio/ogg",
        )

        try:
            async with self._http_session.post(url, data=data) as resp:
                res = await resp.json()
                if res.get("ok"):
                    logger.info("Sent Telegram voice note via Bot API to %s", chat_id)
                    return True
                logger.error("Bot API sendVoice error: %s", res)
                return False
        except Exception as exc:  # noqa: BLE001
            logger.error("HTTP error sending Telegram voice: %s", exc)
            return False

    async def _bot_send_video_note(
        self, chat_id: Any, mp4_path: Path, duration: int | None = None
    ) -> bool:
        """Send video note via Bot API sendVideoNote."""
        if not self._http_session:
            return False

        url = f"https://api.telegram.org/bot{self.cfg.bot_token}/sendVideoNote"
        data = aiohttp.FormData()
        data.add_field("chat_id", str(chat_id))
        data.add_field("length", "384")
        if duration:
            data.add_field("duration", str(duration))

        mp4_bytes = await asyncio.to_thread(mp4_path.read_bytes)
        data.add_field(
            "video_note",
            mp4_bytes,
            filename="video_note.mp4",
            content_type="video/mp4",
        )

        try:
            async with self._http_session.post(url, data=data) as resp:
                res = await resp.json()
                if res.get("ok"):
                    logger.info("Sent Telegram round video note via Bot API to %s", chat_id)
                    return True
                logger.error("Bot API sendVideoNote error: %s", res)
                return False
        except Exception as exc:  # noqa: BLE001
            logger.error("HTTP error sending Telegram video note: %s", exc)
            return False

    # --- Incoming Updates ---

    async def _handle_incoming_telethon_msg(self, event: Any) -> None:
        """Process incoming message from Telethon."""
        try:
            # 1. Ignore broadcast channels, news feeds, and spam channels completely
            if getattr(event, "is_channel", False) and not getattr(event, "is_group", False):
                return

            text = event.raw_text or ""
            chat_id = event.chat_id
            is_private = getattr(event, "is_private", False)
            default_id = str(self.cfg.default_chat_id or "").strip()
            is_default_chat = bool(
                default_id and (str(chat_id) == default_id or str(abs(chat_id)) == default_id)
            )

            # 2. In group chats, only react if Suzu is explicitly mentioned or replied to
            clean_lower = text.lower()
            is_mentioned = (
                "сузу" in clean_lower
                or "suzu" in clean_lower
                or getattr(event, "mentioned", False)
                or is_default_chat
            )

            # If it's a random group/supergroup message without mention or default chat, discard it
            if not is_private and not is_mentioned:
                return

            sender = await event.get_sender()
            sender_name = getattr(sender, "first_name", "") or getattr(sender, "title", "User")
            is_voice = bool(getattr(event, "voice", False))
            is_video_note = bool(getattr(event, "video_note", False))

            logger.info(
                "[Telegram Bridge] Filtered incoming msg from %s (%s, private=%s): %s",
                sender_name,
                chat_id,
                is_private,
                text[:60],
            )
            await self.bus.publish(
                TelegramMessage(
                    chat_id=chat_id,
                    sender_name=sender_name,
                    text=text,
                    is_voice=is_voice,
                    is_video_note=is_video_note,
                )
            )
        except Exception as exc:  # noqa: BLE001
            logger.error("Error processing incoming Telethon message: %s", exc)

    async def _bot_polling_loop(self) -> None:
        """Background long-polling loop for Telegram Bot API."""
        logger.info("Starting Telegram Bot API long-polling loop")
        default_id = str(self.cfg.default_chat_id or "").strip()
        while self._running:
            if not self._http_session:
                await asyncio.sleep(2.0)
                continue

            try:
                url = f"https://api.telegram.org/bot{self.cfg.bot_token}/getUpdates"
                params = {"offset": self._last_update_id + 1, "timeout": 20}
                async with self._http_session.get(url, params=params) as resp:
                    if resp.status != 200:
                        await asyncio.sleep(5.0)
                        continue

                    data = await resp.json()
                    if not data.get("ok"):
                        await asyncio.sleep(5.0)
                        continue

                    for upd in data.get("result", []):
                        self._last_update_id = upd.get("update_id", self._last_update_id)
                        msg = upd.get("message")
                        if not msg:
                            continue

                        chat = msg.get("chat", {})
                        chat_id = chat.get("id", "")
                        chat_type = chat.get("type", "")
                        from_user = msg.get("from", {})
                        sender_name = from_user.get("first_name", "User")
                        text = msg.get("text", "")
                        clean_lower = text.lower()

                        # Only process private chats, default chat, or direct mentions
                        is_mentioned = "сузу" in clean_lower or "suzu" in clean_lower
                        is_default = bool(default_id and str(chat_id) == default_id)
                        if chat_type != "private" and not is_default and not is_mentioned:
                            continue

                        is_voice = "voice" in msg
                        is_video_note = "video_note" in msg

                        logger.info(
                            "[Telegram Bridge] Filtered incoming Bot msg from %s (%s): %s",
                            sender_name,
                            chat_id,
                            text[:60],
                        )
                        await self.bus.publish(
                            TelegramMessage(
                                chat_id=chat_id,
                                sender_name=sender_name,
                                text=text,
                                is_voice=is_voice,
                                is_video_note=is_video_note,
                            )
                        )

            except asyncio.CancelledError:
                break
            except Exception as exc:  # noqa: BLE001
                logger.debug("Bot polling error: %s", exc)
                await asyncio.sleep(5.0)
